def _run_snakemake_dryrun(
    snakefile, workdir, config_path, target=None, printshellcmds=False, extra_args=None
):
    command = [
        SNAKEMAKE,
        "-s",
        snakefile,
        "--configfile",
        config_path,
        "-n",
    ]
    if printshellcmds:
        command.append("-p")
    if target:
        command.append(target)
    # extra_args go last: --config greedily consumes following tokens.
    if extra_args:
        command.extend(extra_args)
    result = subprocess.run(
        command,
        cwd=workdir,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"},
    )
    return result, result.stdout + result.stderr


def _run_snakemake_job(snakefile, workdir, config_path, target, extra_args=None):
    command = [
        SNAKEMAKE,
        "-s",
        snakefile,
        "--configfile",
        config_path,
        "-j",
        "1",
        target,
    ]
    # extra_args go last: --config greedily consumes following tokens.
    if extra_args:
        command.extend(extra_args)
    result = subprocess.run(
        command,
        cwd=workdir,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"},
    )
    return result, result.stdout + result.stderr


_UPDATED_SAMPLES_HEADER = (
    "sample\tfastq_1\tfastq_2\tlayout\tassay\ttarget\tpeak_mode\tgenome\t"
    "bowtie2_index\texperiment\tcondition\treplicate\tbiological_replicate\t"
    "technical_replicate\trole\tcontrol_sample\tcontrol_bam\n"
)


def _write_updated_profile(
    profile_dir,
    sample_rows,
    *,
    use_control,
    genome_resources=None,
    blacklist_mode="off",
    blacklist_path="",
    fragment_cpm=None,
    extend_reads=None,
    tss_fragment_profile=None,
    gtf_path="",
):
    profile_dir.mkdir(parents=True, exist_ok=True)
    (profile_dir / "samples.tsv").write_text(
        _UPDATED_SAMPLES_HEADER + "".join(f"{row}\n" for row in sample_rows),
        encoding="utf-8",
    )
    resources = genome_resources or {
        "hs": {
            "effective_genome_size": "hs",
            "chrom_sizes": "",
            "blacklist": "",
            "gtf": "",
            "reference_fasta": "",
        }
    }
    if blacklist_path:
        resources = {key: dict(value) for key, value in resources.items()}
        resources.setdefault("hs", {})["blacklist"] = blacklist_path
    if gtf_path:
        resources = {key: dict(value) for key, value in resources.items()}
        resources.setdefault("hs", {})["gtf"] = gtf_path
    config = {
        "samples": "samples.tsv",
        "outdir": "results",
        "threads": 1,
        "trim": True,
        "use_control": use_control,
        "multiqc": False,
        "replicate_analysis": True,
        "chipseq_idr": False,
        "genome_resources": resources,
        "qc": {
            "blacklist_filter": False,
            "frip": False,
            "library_complexity": False,
            "nrf_pbc": False,
            "signal_tracks": False,
            "summary": False,
            "cuttag_fragment_size": False,
        },
        "config_schema_version": "2.0.0",
        "analysis_profile": "updated",
        "blacklist_mode": blacklist_mode,
        "organelle_mode": "auto",
        "duplicate_backend": "picard",
        "duplicate_analysis": "exclude",
        "control_mode": "matched",
        "reference_mode": "legacy",
        "external_control_policy": "warn",
        "tss_fragment_profile": False,
    }
    if blacklist_mode == "analysis":
        config["qc"].pop("blacklist_filter", None)
    if fragment_cpm is not None:
        config["fragment_cpm"] = fragment_cpm
    if extend_reads is not None:
        config["extend_reads"] = extend_reads
    if tss_fragment_profile is not None:
        config["tss_fragment_profile"] = tss_fragment_profile
    (profile_dir / "config.yaml").write_text(
        yaml.safe_dump(config, sort_keys=False), encoding="utf-8"
    )
    return prepare_profile_workdir(str(profile_dir))


